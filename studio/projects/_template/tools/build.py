#!/usr/bin/env python3
"""tools/build.py — __PROJECT_SLUG__: ONE source for the data, the facts, the Shot Spec and the browser constants.

The rule (worldfilm stages 2-3): nothing reaches the screen that did not pass through here. This script reads the
files project.world.data_files declares (if any; csv and json are parsed, other formats are read by the project's
own code) and writes
  facts.json      every number / name / date that may appear on screen, with its source, unit, precision and
                  rounding (the facts gate traces displayed tokens to it)
  shotspec.json   the worldfilm Shot Spec: shots, camera pose graph, labels, captions, audio cue summary
  film/data.js    the same timeline for the browser: world.js and film/main.js read nothing else
                  (fps, duration, sizes, shots, the events(t) table, anchors, colours, any precomputed series)
Keep the spec a function of the data: when a value changes, the label text, the fact and the browser constant
change together. Preserve the source's precision, units and rounding; compute discrete counts as integers, exact
decimal quantities with decimal.Decimal, and measured values as floats with a stated tolerance.

Run: python3 tools/build.py            writes everything; exits 2 while a template placeholder (F-EXAMPLE, L-example,
                                       A-example) remains or a declared data file is missing (listed)
     python3 tools/build.py --allow-todo   writes everything and exits 0 (early stages only; build.sh never passes it)
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
os.chdir(ROOT)
todo = []

# ---- 1. the data: the files project.world.data_files declares (none is fine: a geometric or footage-only film may
#         have no data). Compute in the unit and precision each source uses.
spec = json.load(open("shotspec.json"))
proj = spec["project"]
data = {}
for path in (proj.get("world") or {}).get("data_files") or []:
    if not os.path.isfile(path):
        todo.append("project.world.data_files names %s, which does not exist" % path)
    elif path.endswith(".csv"):
        with open(path, newline="") as f:
            data[path] = list(csv.DictReader(f))
    elif path.endswith(".json"):
        data[path] = json.load(open(path))
    else:
        data[path] = None   # read it in the project's own way below

# ---- 2. the facts: one entry per value that reaches the screen, keyed by fact id
facts = json.load(open("facts.json"))
if not isinstance(facts, dict):
    sys.exit("facts.json must be an object keyed by fact id (see templates/facts.template.json)")
# facts["F-TOTAL"] = {"claim": "...", "value": ..., "value_type": "integer", "unit": "...", "precision": "...",
#                     "rounding": "...", "kind": "measurement", "source": "data/....csv", "retrieved": "YYYY-MM-DD", "display": ["..."]}
if "F-EXAMPLE" in facts:
    todo.append("facts.json still holds the F-EXAMPLE placeholder")
unsourced = [fid for fid, f in facts.items() if fid != "F-EXAMPLE" and not f.get("source")]
if unsourced:   # reported, not failed: some facts are stated by the brief itself; say so in their claim
    print("note: facts without a source: %s" % ", ".join(unsourced))

# ---- 3. the spec: load the hand-edited skeleton, then derive what the data decides (shot times, labels, cue times)
FPS, DUR = proj["fps"], proj["duration"]
for s in spec["shots"]:
    for t in s.get("text", []):
        if t.get("id") == "L-example":
            todo.append("shot %s still shows the L-example placeholder label" % s.get("id"))
    for a in s.get("world_anchors", []) or []:
        if a.get("id") == "A-example":
            todo.append("shot %s still carries the A-example placeholder anchor" % s.get("id"))

# ---- 4. the event table events(t): sound cues and labels lock to these (stage 8)
events = []   # e.g. [{"id": "reveal", "t": 4.2, "kind": "reveal"}], derived from the data and the spec; empty is fine
              # for a film with no event-locked sound or labels

# ---- 5. write everything
json.dump(facts, open("facts.json", "w"), indent=1, ensure_ascii=False)
json.dump(spec, open("shotspec.json", "w"), indent=1, ensure_ascii=False)
bpm = (proj.get("music") or {}).get("bpm")
data_js = {
    "fps": FPS, "dur": DUR, "sizes": proj["sizes"], "bpm": bpm, "beat": (60.0 / bpm) if bpm else None,
    "world_seed": (proj.get("world") or {}).get("seed", 1), "world_options": (proj.get("world") or {}).get("options", {}),
    "camera": proj.get("camera", {}), "shots": spec["shots"], "events": events, "colors": proj["brand"]["colors"],
    "labels": {t["id"]: t["content"] for s in spec["shots"] for t in s.get("text", [])},
    "variants": proj.get("variants", []),
}
os.makedirs("film", exist_ok=True)
open("film/data.js", "w").write("// generated by tools/build.py — do not edit\nexport const DATA = " + json.dumps(data_js, ensure_ascii=False) + ";\n")
print("data files %d, facts %d, shots %d, events %d -> facts.json shotspec.json film/data.js" % (len(data), len(facts), len(spec["shots"]), len(events)))
if todo:
    print("UNCONFIGURED (%d):" % len(todo))
    for t in todo:
        print("  - " + t)
    if "--allow-todo" not in sys.argv:
        sys.exit(2)
