#!/usr/bin/env python3
"""tools/build.py — __PROJECT_SLUG__: ONE source for the data, the facts, the Shot Spec and the browser constants.

The rule (worldfilm stage 2-3): nothing reaches the screen that did not pass through here. This script reads the
project's data (data/*.csv, with the source of every number), and writes
  facts.json      every number / name / date that may appear on screen, with its source (the facts gate traces to it)
  shotspec.json   the worldfilm Shot Spec: shots, camera pose graph, labels, captions, audio cue summary
  film/data.js    the same timeline for the browser: world.js and film/main.js read nothing else
                  (fps, dur, shots, events(t) table, anchors, colours, any precomputed series)
Keep the spec a function of the data: when a number changes, the label text, the fact and the browser constant
change together. Worked example: studio/projects/block-space/tools/build.py (311 lines, every value derived).
Run: python3 tools/build.py
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
os.chdir(ROOT)

# ---- 1. the data (TODO): read data/*.csv; compute in the unit the source uses (integers where the protocol pays integers)
rows = []
for name in sorted(os.listdir("data")):
    if name.endswith(".csv"):
        rows += list(csv.DictReader(open(os.path.join("data", name))))

# ---- 2. the facts (TODO): one entry per number that reaches the screen, with its source and retrieval date
facts = json.load(open("facts.json"))                       # starts from templates/facts.template.json; extend it from the data
# facts["facts"].append({"id": "F-TOTAL", "claim": "...", "value": 21000000, "unit": "BTC", "source": "data/schedule.csv", "retrieved": "YYYY-MM-DD"})

# ---- 3. the spec: load the hand-edited skeleton, then derive what the data decides (shot times, labels, cue times)
spec = json.load(open("shotspec.json"))
FPS, DUR = spec["project"]["fps"], spec["project"]["duration"]
BPM = spec["project"].get("music", {}).get("bpm", 120)

# ---- 4. the event table events(t): every sound cue and every label is locked to one of these (stage 8)
events = [{"id": "open", "t": 0.0, "kind": "open"}]           # TODO: the film's events, derived from the data and the spec
# e.g. events += [{"id": "halving-%d" % k, "t": t, "kind": "halving"} for k, t in ...]

# ---- 5. write everything
json.dump(facts, open("facts.json", "w"), indent=1)
json.dump(spec, open("shotspec.json", "w"), indent=1)
data_js = {
    "fps": FPS, "dur": DUR, "bpm": BPM, "beat": 60.0 / BPM, "world_seed": spec["project"].get("world", {}).get("seed", 1),
    "shots": spec["shots"], "events": events, "colors": spec["project"]["brand"]["colors"],
    "labels": {t["id"]: t["content"] for s in spec["shots"] for t in s.get("text", [])},
    "variants": spec["project"].get("variants", []),
}
os.makedirs("film", exist_ok=True)
open("film/data.js", "w").write("// generated by tools/build.py — do not edit\nexport const DATA = " + json.dumps(data_js) + ";\n")
print("rows %d, facts %d, shots %d, events %d -> facts.json shotspec.json film/data.js" % (len(rows), len(facts.get("facts", [])), len(spec["shots"]), len(events)))

